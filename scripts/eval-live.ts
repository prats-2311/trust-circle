import { mkdirSync, writeFileSync } from "node:fs";
import { createGroqJudge } from "../src/ai/groqJudge";
import { createGroqMessageJudge } from "../src/ai/groqMessageJudge";
import { createPromptGuard } from "../src/ai/promptGuard";
import { EVAL_CASES } from "../src/eval/cases";
import { createLocalEmbedder } from "../src/patterns/embedder";
import { createMemoryPatternMatcher } from "../src/eval/memoryPatterns";
import { PATTERNS } from "./seed-pattern-list";
import { matcherEffect } from "../src/eval/matcherEffect";
import { rulesOnlyComparison } from "../src/eval/rulesOnly";
import { PATTERN_THRESHOLD } from "../src/patterns/patternService";
import { runEval, type EvalResult } from "../src/eval/runEval";

const CATCH_GATE = 0.9;
const FALSE_HOLD_GATE = 0.1;
// The last run with the matcher off (2026-10-16, before Plan 5 Task 2): 2 false alarms out of 28 genuine cases.
const BASELINE_DATE = "2026-10-16";
const BASELINE_FALSE_ALARMS = 2;
const pct = (n: number) => `${Math.round(n * 100)}%`;

async function main() {
  const apiKey = process.env.GROQ_API_KEY;
  const textModel = process.env.GROQ_TEXT_MODEL;
  const visionModel = process.env.GROQ_VISION_MODEL;
  const guardModel = process.env.GROQ_GUARD_MODEL || "meta-llama/llama-prompt-guard-2-86m";
  if (!apiKey || !textModel || !visionModel) throw new Error("GROQ_API_KEY, GROQ_TEXT_MODEL and GROQ_VISION_MODEL are required");

  const patterns = await createMemoryPatternMatcher(createLocalEmbedder(), PATTERNS);
  const { results, metrics } = await runEval(EVAL_CASES, {
    paymentJudge: createGroqJudge({ apiKey, model: textModel }),
    messageJudge: createGroqMessageJudge({ apiKey, textModel, visionModel }),
    guard: createPromptGuard({ apiKey, model: guardModel }),
    patterns,
    pauseMs: 2500, // stays inside Groq's free-tier request rate
    onResult: (r) => console.log(`${r.id} ${r.label.padEnd(7)} -> ${r.level}${r.checked ? "" : " (AI unavailable)"}${r.attempts > 1 ? " (retried)" : ""}`),
  });

  const wrong = (r: EvalResult) => (r.label === "scam" ? r.level === "low" : r.level !== "low") || !r.checked;
  const rows = results
    .filter(wrong)
    .map((r) => `| ${r.id} | ${r.kind} | ${r.preset} | ${r.label} | ${r.level}${r.checked ? "" : " (unchecked)"} | ${r.attempts} | ${r.signals.join(", ") || "none"} |`);
  const unchecked = results.filter((r) => !r.checked);
  const retried = results.filter((r) => r.attempts > 1);
  const effect = matcherEffect(results);
  const cmp = rulesOnlyComparison(results);
  const p = cmp.payments;
  const of = (n: number, d: number) => `${n} of ${d}`;
  const ids = (l: string[]) => (l.length ? ` (${l.join(", ")})` : "");
  const recovered = retried.filter((r) => r.checked).length;
  const passed = metrics.catchRate >= CATCH_GATE && metrics.falseHoldRate <= FALSE_HOLD_GATE;
  const md = [
    "# Evaluation results",
    "",
    `Run ${new Date().toISOString().slice(0, 10)} on ${metrics.total} invented cases (${metrics.scams} scams, ${metrics.genuine} genuine) against Groq: text model \`${textModel}\`, injection screen \`${guardModel}\`. Generated by \`npm run eval:live\`.`,
    "",
    `Pattern matcher: on (${PATTERNS.length} known patterns, threshold ${PATTERN_THRESHOLD}).`,
    "",
    "| Measure | Result |",
    "|---|---|",
    `| Scams flagged (warning or hold) | ${metrics.caught} of ${metrics.scams} (${pct(metrics.catchRate)}) |`,
    `| Scams held | ${metrics.held} of ${metrics.scams} (${pct(metrics.holdRate)}) |`,
    `| Genuine cases given a warning or hold | ${metrics.falseAlarms} of ${metrics.genuine} (${pct(metrics.falseAlarmRate)}) |`,
    `| Genuine cases held | ${metrics.falseHolds} of ${metrics.genuine} (${pct(metrics.falseHoldRate)}) |`,
    `| Cases the AI could not check after one retry | ${metrics.unchecked} |`,
    `| Cases that needed a retry | ${retried.length} (${recovered} recovered) |`,
    "",
    `Gate: at least ${pct(CATCH_GATE)} of scams flagged and at most ${pct(FALSE_HOLD_GATE)} of genuine cases held. Result: ${passed ? "pass" : "fail"}.`,
    "",
    "## Misses, false alarms and unchecked cases",
    "",
    ...(rows.length ? ["| Case | Kind | Preset | Label | Level | Attempts | Signals |", "|---|---|---|---|---|---|---|", ...rows] : ["None."]),
    "",
    "## Unchecked after retry",
    "",
    ...(unchecked.length
      ? ["| Case | Label | Level shown | Cause |", "|---|---|---|---|", ...unchecked.map((r) => `| ${r.id} | ${r.label} | ${r.level} | ${r.uncheckedCause ?? "unknown"} |`)]
      : ["None."]),
    "",
    "## What the AI adds",
    "",
    `Scored from the same run, with no extra AI calls. "Rules alone" uses only the rule signals (first-time payee, unusual amount, over the circle limit, rapid repeats, the scam list), without Prompt Guard or the pattern matcher. "AI unavailable" is the app's fallback: any rule signal holds the payment.`,
    "",
    `| Payments (${p.scams} scams, ${p.genuine} genuine) | Scams held | Scams flagged | Genuine held | Genuine flagged |`,
    "|---|---|---|---|---|",
    `| Rules and AI (as the app runs) | ${of(p.withAi.scamsHeld, p.scams)} | ${of(p.withAi.scamsFlagged, p.scams)} | ${of(p.withAi.genuineHeld, p.genuine)} | ${of(p.withAi.genuineFlagged, p.genuine)} |`,
    `| Rules alone | ${of(p.rulesAlone.scamsHeld, p.scams)} | ${of(p.rulesAlone.scamsFlagged, p.scams)} | ${of(p.rulesAlone.genuineHeld, p.genuine)} | ${of(p.rulesAlone.genuineFlagged, p.genuine)} |`,
    `| AI unavailable (fallback) | ${of(p.aiUnavailable.scamsHeld, p.scams)} | ${of(p.aiUnavailable.scamsFlagged, p.scams)} | ${of(p.aiUnavailable.genuineHeld, p.genuine)} | ${of(p.aiUnavailable.genuineFlagged, p.genuine)} |`,
    "",
    `No rules-only setting matches the AI. Holding only what the rules rate high holds ${p.rulesAlone.scamsHeld} of ${p.scams} scams. Holding everything the rules warn about holds ${p.rulesAlone.scamsFlagged} of ${p.scams} scams and ${p.rulesAlone.genuineFlagged} of ${p.genuine} genuine payments. The AI can only raise a rule's level, never lower it, so genuine payments the rules warn about keep their warning (they still go through).`,
    "",
    `Scam payments only the AI held${ids(p.onlyAiHeld)}: ${p.onlyAiHeld.length}. Messages have no rules-only score: the rules only look at payments. Of the ${cmp.messages.scams} scam messages, the AI checked ${cmp.messages.aiChecked} and flagged ${cmp.messages.withAiFlagged} of those (the rest timed out and were shown as unchecked, never as safe).`,
    "",
    "## Pattern matcher's effect",
    "",
    `${effect.withPattern.length} of the ${effect.falseAlarms} false alarms on genuine cases carry KNOWN_SCAM_PATTERN${ids(effect.withPattern)}. ${effect.heldOnPatternAlone.length} genuine case(s) were held on that signal alone${ids(effect.heldOnPatternAlone)}. The last run with the matcher off (${BASELINE_DATE}) had ${BASELINE_FALSE_ALARMS} false alarms out of 28 genuine cases (the 60-case set before the hard cases were added), so the matcher catches reworded scams at the cost of more warnings on everyday payments. The seed patterns are likely too broad for some ordinary messages.`,
    "",
    "## What these numbers mean",
    "",
    `When the AI cannot check a payment, Trust Circle fails closed: the rules hold it, so an unchecked scam payment counts as held and an unchecked genuine payment counts as a false hold. A message the AI cannot check is shown as unchecked, never as safe, but the scoring here still counts an unchecked scam message as a miss. Each unchecked case gets one retry, after twice the normal pause, and the cause above is the error the AI service returned on the last attempt. The set is ${metrics.total} hand-written cases, so these numbers show behaviour on known situations, not real-world rates. This is a single run: ${retried.length} of the ${metrics.total} cases needed a retry, and a repeat run can differ slightly.`,
    "",
  ].join("\n");
  mkdirSync("docs/eval", { recursive: true });
  writeFileSync("docs/eval/results.md", md);
  console.log(`\ncatch ${pct(metrics.catchRate)}, false holds ${pct(metrics.falseHoldRate)}: ${passed ? "PASS" : "FAIL"}`);
  process.exitCode = passed ? 0 : 1;
}

main().catch((e) => {
  console.error(e instanceof Error ? e.message : "failed");
  process.exit(1);
});
